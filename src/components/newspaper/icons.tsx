export type IconProps = SVGProps<SVGSVGElement> & { size?: number };

function make(paths: ReactNode, label: string) {
  function Icon({ size = 16, ...rest }: IconProps) {
    return (
      <svg
        width={size}
        height={size}
        viewBox="0 0 24 24"
        fill="none"
        stroke="currentColor"
        strokeWidth={2}
        strokeLinecap="round"
        strokeLinejoin="round"
        aria-hidden="true"
        focusable="false"
        data-icon={label}
        {...rest}
      >
        {paths}
      </svg>
    );
  }
  Icon.displayName = `Icon${label}`;
  return Icon;
}

